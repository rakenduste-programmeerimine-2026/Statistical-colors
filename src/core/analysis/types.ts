/** Options the user picks on the upload form. */
export interface AnalysisOptions {
  /** Count colours as RGBA instead of RGB. */
  includeAlpha: boolean;
  /** How many of the most frequent colours the results page shows. */
  topN: number;
}

/** One unique colour and how often it occurs. */
export interface ColorCount {
  r: number;
  g: number;
  b: number;
  /** Alpha 0–255, only present when the analysis includes alpha. */
  a?: number;
  count: number;
  /** Share of all pixels, 0–100. */
  percent: number;
}

/** Summary of one analysed image, as the results page needs it. */
export interface ImageAnalysis {
  id: string;
  fileName: string;
  width: number;
  height: number;
  totalPixels: number;
  uniqueColors: number;
  includeAlpha: boolean;
  /** Top N chosen on upload; the results page can override it. */
  topN: number;
  /** Most frequent colours first. Holds at least `topN` entries when that many exist. */
  colors: ColorCount[];
  /** True when the data was generated by the stub, not computed from the image. */
  simulated?: boolean;
}

export type CsvKind = "pixels" | "summary";

export interface CsvFile {
  fileName: string;
  content: Blob;
}
