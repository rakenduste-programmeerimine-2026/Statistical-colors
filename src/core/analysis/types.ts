import type { ImageFormat } from "../image-format";
import type { ColorAnalysis } from "./color-analysis";

/** Options the user picks on the upload form. */
export interface AnalysisOptions {
  /** Count colours as RGBA instead of RGB. */
  includeAlpha: boolean;
  /** How many of the most frequent colours the results page shows. */
  topN: number;
}

/** One unique colour and how often it occurs. */
export interface ColorCount {
  r: number;
  g: number;
  b: number;
  /** Alpha 0–255, only present when the analysis includes alpha. */
  a?: number;
  count: number;
  /** Share of all pixels, 0–100. */
  percent: number;
  /**
   * The server's likelihood (0–1) that this colour is a blend pixel
   * (segupiksel, `artefact.antialias-blend`) or another artefact, per registry
   * kind (docs/ontology/07-digital-artefacts.md). Sent by the server (#69, P-033 item 1).
   */
  artefacts?: ColorArtefact[];
  /** The `colorAnalysis.palette` cluster this colour belongs to (#69, P-033 item 2). */
  clusterId?: string;
}

export interface ColorArtefact {
  kind: string;
  chance: number;
}

/** Summary of one analysed image, as the results page needs it. */
export interface ImageAnalysis {
  id: string;
  fileName: string;
  width: number;
  height: number;
  totalPixels: number;
  uniqueColors: number;
  includeAlpha: boolean;
  /** The decoded file format, when it was stored (images.format). */
  format?: ImageFormat;
  /** Top N chosen on upload; the results page can override it. */
  topN: number;
  /**
   * Most frequent colours first. Holds at least `topN` entries when that many
   * exist; once #69 is done, every colour, so filters reach beyond the top N.
   */
  colors: ColorCount[];
  /** Whether `colors[].artefacts` and `clusterId` were computed by the server or simulated (P-033 item 1). */
  rowDataStatus?: "computed" | "simulated";
  /** True when the data was generated by the stub, not computed from the image. */
  simulated?: boolean;
  /** True for the built-in example result from the earlier colour picker study. */
  example?: boolean;
  /** URL of the analysed image for the pixel preview, when it is stored (#39). */
  imageUrl?: string;
  /** The server's colour analysis (P-031); absent until the server sends one. */
  colorAnalysis?: ColorAnalysis;
}

export type CsvKind = "pixels" | "summary";

export interface CsvFile {
  fileName: string;
  content: Blob;
}
